    test("brightness: the backlight's name and its share of the maximum", function()
        local b = D.brightness("intel_backlight,backlight,4800,50%,9600\n")
        eq(b.device, "intel_backlight", "the device")
        eq(b.frac, 0.5, "4800 of 9600")
