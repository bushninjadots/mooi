    eq(wallpaper.edges_of(back, "/a.png")[2], "#214161", "read back from the file")
    local bad = wallpaper.state({ edges = { ["/b.png"] = { c = { "nonsense", "#000000", "#000000" } } } })
    eq(wallpaper.edges_of(bad, "/b.png"), nil, "a colour that is not one is refused")
    eq(wallpaper.remember_edges(s, "/c.png", { "#000000", "#000000" }, 11), s, "two colours are not enough")
    local old = wallpaper.RECIPES_MAX; wallpaper.RECIPES_MAX = 1
