local theme = require("lib/theme")
local matugen_dark = { version = 1, mode = "dark", colours = {
    surface_dim = "#16130b", surface_container_low = "#1e1b13", surface_container = "#221f17",
    surface_container_high = "#2d2a21", outline_variant = "#4b4639", outline = "#979080",
    on_surface = "#e9e2d4", on_surface_variant = "#cec6b4", primary = "#dfc56d", error = "#ffb4ab",
} }
test("hex parses, round-trips and refuses what is not a colour", function()
    local c = theme.hex("#A6F3D1"); eq(theme.to_hex(c), "#A6F3D1", "round trip")
    eq(theme.hex("A6F3D1"), nil, "no hash"); eq(theme.hex("#fff"), nil, "short"); eq(theme.hex(12), nil, "number")
    eq(math.abs(c.r - 0.6510) < 0.001, true, "red")
end)
test("contrast matches WCAG for known pairs", function()
    local white, black = theme.hex("#FFFFFF"), theme.hex("#000000")
    eq(math.floor(theme.contrast(white, black) + 0.5), 21, "white on black")
    eq(theme.contrast(white, white), 1, "same colour")
end)
test("the fixed palette is complete and passes its own check", function()
    eq(#theme.TOKENS, 14, "tokens")
    for _, t in ipairs(theme.TOKENS) do eq(type(theme.hex(theme.FIXED[t])), "table", t) end
    eq(#theme.check(theme.resolve({ source = "fixed" })), 0, "no problems")
end)
test("a wallpaper palette fills the tokens from Matugen roles", function()
    local colours, source, notes, problems = theme.resolve({ source = "wallpaper" }, matugen_dark)
    eq(source, "wallpaper", "source"); eq(#problems, 0, "passes")
    eq(theme.to_hex(colours["bg.primary"]), "#16130B", "bg.primary from surface_dim")
    eq(theme.to_hex(colours["accent.primary"]), "#DFC56D", "accent from primary")
    eq(theme.to_hex(colours["status.error"]), "#FFB4AB", "error role")
    eq(notes[1], nil, "nothing to report")
end)
test("selection.bg is the background with a little accent, and stays dark", function()
    local colours = theme.resolve({ source = "wallpaper" }, matugen_dark)
    local sel, bg, accent = colours["selection.bg"], colours["bg.primary"], colours["accent.primary"]
    eq(sel.r > bg.r and sel.r < accent.r, true, "between the two")
    eq(theme.contrast(colours["fg.primary"], sel) > 4.5, true, "text on it is readable")
end)
test("an override wins over the palette, and is reported", function()
    local colours, _, notes, problems = theme.resolve(
        { source = "wallpaper", overrides = { ["accent.primary"] = "#00FF00", ["nonsense"] = "#FFFFFF", ["fg.primary"] = "green" } },
        matugen_dark)
    eq(theme.to_hex(colours["accent.primary"]), "#00FF00", "override wins")
    eq(#problems, 0, "still valid")
    eq(notes[1], "override fg.primary: not a colour like #A6F3D1; ignored", "bad colour ignored")
    eq(notes[2], "override for unknown token nonsense; ignored", "unknown token ignored")
    eq(notes[3], "user overrides: accent.primary", "what was used")
end)
test("no palette, or a broken one, means the fixed palette and a note", function()
    local colours, _, notes, problems = theme.resolve({ source = "wallpaper" }, nil)
    eq(theme.to_hex(colours["accent.primary"]), "#A6F3D1", "fixed"); eq(#problems, 0, "usable")
    eq(notes[1], "no palette from the wallpaper yet; the fixed palette is showing", "says why")
    local broken = { colours = { primary = "#dfc56d" } }
    local c2, _, notes2 = theme.resolve({ source = "wallpaper" }, broken)
    eq(theme.to_hex(c2["accent.primary"]), "#A6F3D1", "still fixed")
    eq(string.find(notes2[1], "the palette is missing surface_dim") ~= nil, true, "names a role it is missing")
end)
test("a theme that cannot be read is refused whole", function()
    local dark = { colours = { on_surface = "#1a1a18", on_surface_variant = "#20201c", outline = "#26261f" } }
    for role, value in pairs(matugen_dark.colours) do dark.colours[role] = dark.colours[role] or value end
    local _, _, _, problems = theme.resolve({ source = "wallpaper" }, dark)
    eq(#problems > 0, true, "problems found")
    eq(string.find(problems[1], "fg.primary on bg.primary is only") ~= nil, true, "names the pair")
end)
test("a complete but unreadable palette is refused, token by token", function()
    local colours = theme.resolve({ source = "fixed" })
    colours["fg.muted"] = colours["bg.primary"]
    local problems = theme.check(colours)
    eq(#problems, 3, "fg.muted on its three surfaces")
    eq(colours["fg.primary"] ~= nil, true, "a copy, not the table itself")
end)

