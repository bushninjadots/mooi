    eq(position, 0, "zero duration position"); eq(progress, 0, "zero duration progress")
    position, progress = nexus.media_progress("bad", 100)
    eq(position, 0, "invalid position"); eq(progress, 0, "invalid position progress")
    position, progress = nexus.media_progress(20, "bad")
    eq(position, 0, "invalid duration position"); eq(progress, 0, "invalid duration progress")
end)

