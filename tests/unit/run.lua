test("media progress clamps position to valid duration", function()
    local position, progress = nexus.media_progress(30, 120)
    eq(position, 30, "position preserved"); eq(progress, 0.25, "quarter progress")
    position, progress = nexus.media_progress(140, 120)
    eq(position, 120, "position clamped to duration"); eq(progress, 1, "progress clamped to one")
    position, progress = nexus.media_progress(-5, 120)
    eq(position, 0, "negative position clamped"); eq(progress, 0, "negative progress clamped")
end)
