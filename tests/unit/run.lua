test("wallpaper: the background is keyed out into the backdrop", function()
    eq(wallpaper.clean({}).key, 0, "no key by default"); eq(wallpaper.clean({}).key_fuzz, 18, "a fuzz")
    eq(wallpaper.clean({ key = 5 }).key, 1, "the key clamps on"); eq(wallpaper.clean({ key_fuzz = 999 }).key_fuzz, 45, "fuzz clamps")
    eq(wallpaper.BG_INDEX.corners, 2, "corners are the second backdrop"); eq(wallpaper.BG_NAME[5], "both", "and both the fifth")

    -- The background is found by flooding from the picture's border (D62): what the edge is made of
    -- goes, and only what is joined to it — a white eye inside the subject is not part of it.
    local keyed = table.concat(wallpaper.args({ key = 1, key_fuzz = 12 }, "/b.jpg", "/o.jpg", 1600, 900, 1920, 1080,
                                               { mode = 0 }), " ")
    eq(keyed:find("-alpha set", 1, true) ~= nil, true, "an alpha channel is made")
    eq(keyed:find("-fuzz 12%", 1, true) ~= nil, true, "with the fuzz asked for")
    eq(keyed:find("-fill none", 1, true) ~= nil, true, "the hole is filled with nothing")
    eq(keyed:find("alpha 0,0 floodfill", 1, true) ~= nil, true, "from the top left")
    eq(keyed:find("alpha 1599,899 floodfill", 1, true) ~= nil, true, "to the bottom right")
    eq(keyed:find("alpha 800,0 floodfill", 1, true) ~= nil, true, "and the edge's middle")
    eq(select(2, keyed:gsub("floodfill", "")) >= 8, true, "eight points round the border")
    eq(keyed:find("-transparent", 1, true), nil, "no colour key: the picture's own background, not every pixel of a colour")
    eq(keyed:find("-size 1600x900 xc:#000000", 1, true) ~= nil, true, "a full-size fill behind it")
    eq(keyed:find("-resize 1600x900!", 1, true) ~= nil, true, "the picture is not inset by the key alone")
    eq(keyed:find("-composite", 1, true) ~= nil, true, "and is drawn over the fill")

    -- The hole is made last, so a grade or its grain cannot put the transparency back.
    local deep = table.concat(wallpaper.args({ key = 1, grain = 20, vignette = 20 }, "/b.jpg", "/o.jpg", 1600, 900, 1920, 1080,
                                              { mode = 0 }), " ")
    eq(deep:find("floodfill", 1, true) > deep:find("+noise", 1, true), true, "keyed after the grain")
    eq(deep:find("floodfill", 1, true) > deep:find("radial-gradient", 1, true), true, "and after the vignette")
    eq(deep:find("-channel RGB", 1, true) ~= nil, true, "grain keeps its hands off the transparency")
    eq(deep:find("+channel", 1, true) ~= nil, true, "and gives the channels back")
    eq(wallpaper.summary({ key = 1 }):find("KEYED", 1, true) ~= nil, true, "the record says it is keyed")

    -- And a custom colour is what the hole is filled with.
    local custom = table.concat(wallpaper.args({ key = 1, bg = 5, bg_custom = "#c02040" }, "/b.jpg", "/o.jpg",
                                                1600, 900, 1920, 1080, { mode = 5, hex = "#c02040" }), " ")
    eq(custom:find("-size 1600x900 xc:#c02040", 1, true) ~= nil, true, "the typed colour fills behind the key")
end)
test("wallpaper: the edges read are kept in the file", function()
    local s = wallpaper.state(nil)
    eq(wallpaper.edges_of(s, "/a.png"), nil, "nothing read yet")
    wallpaper.remember_edges(s, "/a.png", { "#204060", "#214161", "#204060" }, 10)
