#!/usr/bin/env python3
"""Generates the widgets' lanes in shell/mooi-widgets.plm (D140, D141): the widgets whose lists cannot
sit inside the widgets' loop — the notes, GitHub (two), weather, system, calendar and the launcher —
each drawn by a group of its own that reads its own facts (nl_x, g1_x …). Two blocks are written:
the facts (between `// <gen:lanefacts>` and `// </gen:lanefacts>`) and the groups (between
`// <gen:lanes>` and `// </gen:lanes>`). Every lane gets the same treatment as a widget in the loop:
its place and size (and the size in the hand while it is pulled), its rest, the look (wg_style), the
ambient rest, and desk mode. Never hand-edit those blocks: change this and run it.

  tools/gen-wlanes.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SCENE = ROOT / "shell" / "mooi-widgets.plm"

# prefix, what draws it ({X} {Y} {W} {H} {U} {LAY} {PLATE} ink acc {HZ} {TN})
LANES = [
    ("nl", "wg.NotesList({X}, {Y}, {W}, {H}, {U}, {PLATE}, ink, acc, {HZ}, {TN})"),
    ("g1", "wgh.Gh1({X}, {Y}, {W}, {H}, {U}, {LAY}, {PLATE}, ink, acc, {HZ}, {TN})"),
    ("g2", "wgh.Gh2({X}, {Y}, {W}, {H}, {U}, {LAY}, {PLATE}, ink, acc, {HZ}, {TN})"),
    ("wh", "wx.Weather({X}, {Y}, {W}, {H}, {U}, {LAY}, {PLATE}, ink, acc, {HZ}, {TN})"),
    ("sp", "wx.System({X}, {Y}, {W}, {H}, {U}, {LAY}, {PLATE}, ink, acc, {HZ}, {TN})"),
    ("cd", "wx.CalMonth({X}, {Y}, {W}, {H}, {U}, {PLATE}, ink, acc, {HZ}, {TN})"),
    ("ln", "group {{ show: {LAY} < 1.5\n                wx.Launch({X}, {Y}, {W}, {H}, {U}, {LAY}, {PLATE}, ink, acc, {HZ}, {TN}) }}\n"
           "            group {{ show: {LAY} > 1.5\n                wb.LaunchGrid({X}, {Y}, {W}, {H}, {U}, {PLATE}, ink, acc, {HZ}, {TN}) }}"),
    # D215: the widgets below
    ("nc", "wb.Notices({X}, {Y}, {W}, {H}, {U}, {PLATE}, ink, acc, {HZ}, {TN})"),
    ("wp", "wb.Walls({X}, {Y}, {W}, {H}, {U}, {PLATE}, ink, acc, {HZ}, {TN})"),
    ("pg", "wb.Pages({X}, {Y}, {W}, {H}, {U}, {PLATE}, ink, acc, {HZ}, {TN})"),
    ("ct", "wb.Controls({X}, {Y}, {W}, {H}, {U}, {LAY}, {PLATE}, ink, acc, {HZ}, {TN})"),
]

FACTS = [("on", "false"), ("above", "false"), ("k", "0"), ("x", "0"), ("y", "0"), ("w", "10"), ("h", "10"), ("u", "1"), ("lay", "0"),
         ("st", "0"), ("gh", "false"), ("opa", "1"), ("beh", "false"), ("plate", "false"), ("sel", "false"),
         ("tn", "0"), ("hz", "0.32"), ("ad", "false"), ("ar", "0.6"), ("ag", "0.8"), ("ab", "0.7"), ("dx", "0"), ("dy", "0")]

PO = ", ".join(f"po{i}" for i in range(16))
RU = ", ".join(f"ru{i}" for i in range(16))

# The look shared with the loop (mooi-widgets.plm writes the same for the widgets in it).
INK = "pick(wg_style, if({p}_ad, if({p}_tn > 0.5, #15181c, #eef1f4), fl.engrave), #dcffe9, #16191c, #f2f5f8, #2b2722)"
ACC = "pick(wg_style, if({p}_ad, rgb({p}_ar, {p}_ag, {p}_ab), fl.phos), fl.phos, fl.ember, #a9c4dc, #b4532f)"


def facts():
    out = ["    // GENERATED by tools/gen-wlanes.py — each lane's place, size, rest and look (lib/widgets)"]
    for p, _ in LANES:
        out += [f"    fact {p}_{n} = {v}" for n, v in FACTS]
    return "\n".join(out)


def lanes():
    out = ["        // GENERATED by tools/gen-wlanes.py — the notes, GitHub, weather, system, calendar, launcher and D215 lanes"]
    for p, call in LANES:
        rz = f"wg_rk == {p}_k"
        args = dict(X=f"if({rz}, wg_sx, {p}_x)", Y=f"if({rz}, wg_sy, {p}_y)", W=f"if({rz}, wg_sw, {p}_w)",
                    H=f"if({rz}, wg_sh, {p}_h)", U=f"if({rz}, wg_ru, {p}_u)", LAY=f"{p}_lay", PLATE=f"{p}_plate",
                    HZ=f"{p}_hz", TN=f"{p}_tn")
        along = f"(wg_dk == {p}_k or (wg_dk >= 0 and wg_dksel and {p}_sel))"
        # the notes lane carries its own text field: while it is being edited it is whole and unclipped
        edit = " or nt_ed > -1.5" if p == "nl" else ""
        clip_edit = " and nt_ed < -1.5" if p == "nl" else ""
        out.append(f"""        // how near the pointer is to it (the ambient rest lifts as it comes), and how seen it is
        let {p}_near = clamp(1 - max(max(0, max({p}_x - desk.cursor.x, desk.cursor.x - {p}_x - {p}_w)), max(0, max({p}_y - desk.cursor.y, desk.cursor.y - {p}_y - {p}_h))) / 220, 0, 1)
        let {p}_wake = {p}_near > 0.7
        on change {p}_wake while {p}_wake and wg_amb and {p}_on {{ wg_amb = false }}
        // D220: below the wallpaper, inside the opening, it is awake — never at its rest, never dimmed
        let {p}_opn = sf_on and op_vis and not {p}_above and not editing and not wg_desk
        let {p}_base = if(editing, if({p}_gh, 0.4, 1), if({p}_opn, 1, if(viz_still, if({p}_st < 0.5, 1, 0.35), pick({p}_k, {PO})))) * {p}_opa * if({p}_opn, 1, 1 - 0.85 * wg_ambs * (1 - {p}_near))
        // coming up (D216): below, it waits at 96 % and faded until the opening snaps to it (outside the
        // group: a group's own settings cannot read its lets)
        let {p}_rs = if(sf_on and not {p}_above and not editing and not wg_desk{clip_edit}, pick({p}_k, {RU}), 1)
        group {{
            let ink = {INK.format(p=p)}
            let acc = {ACC.format(p=p)}
            z: if({p}_beh, 1, 3)
            // D209: below the wallpaper it is only there while the opening shows, and only inside the hole
            show: (not sf_on or {p}_above or editing or wg_desk or (op_vis and not wg_quiet){edit}) and {p}_on and (editing or wg_dkp > 0.01 or {p}_opn or {p}_st < 1.5)
            let {p}_clip = sf_on and not {p}_above and not editing and not wg_desk{clip_edit}
            opacity: ({p}_base + (1 - {p}_base) * wg_dkp) * (0.72 + 0.28 * {p}_rs)
            pivot: {args["X"]} + {args["W"]} / 2, {args["Y"]} + {args["H"]} / 2
            scale: 0.96 + 0.04 * {p}_rs
            move: if({along}, wg_dx, 0) + {p}_dx * wg_dkp, if({along}, wg_dy, 0) + {p}_dy * wg_dkp
            clip box {{ from: if({p}_clip, op_x, 0), if({p}_clip, op_y - wall_bar, 0); size: if({p}_clip, op_w, desk.width), if({p}_clip, op_h, desk.height); corner: if({p}_clip, op_r, 0) }}
            group {{ glow: 26, 0.55 * {p}_rs, #000000; show: {p}_clip and {p}_rs > 0.01
                box {{ from: {args["X"]}, {args["Y"]}; size: {args["W"]}, {args["H"]}; corner: 6 * {args["U"]}; color: #000000; opacity: 0.2 * {p}_rs }} }}
            {call.format(**args)}
            box {{ from: {p}_x, {p}_y; size: {p}_w, {p}_h; corner: 6; stroke: 1; color: fl.trace_lit; opacity: 0.4 * wg_ambs * (1 - {p}_near) }}
        }}""")
    return "\n".join(out)


def rise():
    """Coming up (the Subsurface spec §6, D216): mooi-surface says which slot the opening snaps to (wg_rise); that
    widget rises to its full size on a spring, the others below wait at 96 % and faded, and in a section every
    one rises. Springs only, never a long tween (D152)."""
    out = ["    // GENERATED by tools/gen-wlanes.py — coming up: which widget the opening hugs, and each slot's rise",
           "    event wg_rise ->             // from mooi-surface: the slot the opening snaps to, or -1",
           "    event wg_press ->            // from mooi-surface: Return on a snapped widget (its slot)",
           "    fact wg_rise = -1",
           "    on wg_rise(v) { wg_rise = v }",
           "    spring wg.rise = 320, 26"]
    for k in range(16):
        out += [f"    prop ru{k} = 0 ~wg.rise",
                f"    follow ru{k} = if(op_vis and (op_mode == 3 or wg_rise == {k}), 1, 0)"]
    return "\n".join(out)


def put(text, tag, body):
    pat = re.compile(rf"( *)// <gen:{tag}>\n.*?// </gen:{tag}>", re.S)
    m = pat.search(text)
    if not m:
        raise SystemExit(f"no <gen:{tag}> block in {SCENE}")
    ind = m.group(1)
    return text[:m.start()] + f"{ind}// <gen:{tag}>\n{body}\n{ind}// </gen:{tag}>" + text[m.end():]


def main():
    text = SCENE.read_text()
    text = put(text, "lanefacts", facts())
    text = put(text, "lanes", lanes())
    text = put(text, "rise", rise())
    SCENE.write_text(text)
    print(f"wrote the lanes in {SCENE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
