#!/usr/bin/env python3
"""Generates the widgets' lanes in shell/mooi-widgets.plm (D140, D141): the widgets whose lists cannot
sit inside the widgets' loop — the notes, GitHub (two), weather, system, calendar and the launcher —
each drawn by a group of its own that reads its own facts (nl_x, g1_x …). Two blocks are written:
the facts (between `// <gen:lanefacts>` and `// </gen:lanefacts>`) and the groups (between
`// <gen:lanes>` and `// </gen:lanes>`). Every lane gets the same treatment as a widget in the loop:
its place and size (and the size in the hand while it is pulled), its rest, the look (wg_style), the
ambient rest, and desk mode. Never hand-edit those blocks: change this and run it.

  tools/gen-wlanes.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SCENE = ROOT / "shell" / "mooi-widgets.plm"

# prefix, what draws it ({X} {Y} {W} {H} {U} {LAY} {PLATE} ink acc {HZ} {TN})
LANES = [
    ("nl", "wg.NotesList({X}, {Y}, {W}, {H}, {U}, {PLATE}, ink, acc, {HZ}, {TN})"),
    ("g1", "wgh.Gh1({X}, {Y}, {W}, {H}, {U}, {LAY}, {PLATE}, ink, acc, {HZ}, {TN})"),
    ("g2", "wgh.Gh2({X}, {Y}, {W}, {H}, {U}, {LAY}, {PLATE}, ink, acc, {HZ}, {TN})"),
    ("wh", "wx.Weather({X}, {Y}, {W}, {H}, {U}, {LAY}, {PLATE}, ink, acc, {HZ}, {TN})"),
    ("sp", "wx.System({X}, {Y}, {W}, {H}, {U}, {LAY}, {PLATE}, ink, acc, {HZ}, {TN})"),
    ("cd", "wx.CalMonth({X}, {Y}, {W}, {H}, {U}, {PLATE}, ink, acc, {HZ}, {TN})"),
    ("ln", "wx.Launch({X}, {Y}, {W}, {H}, {U}, {LAY}, {PLATE}, ink, acc, {HZ}, {TN})"),
]

FACTS = [("on", "false"), ("k", "0"), ("x", "0"), ("y", "0"), ("w", "10"), ("h", "10"), ("u", "1"), ("lay", "0"),
         ("st", "0"), ("gh", "false"), ("opa", "1"), ("beh", "false"), ("plate", "false"), ("sel", "false"),
         ("tn", "0"), ("hz", "0.32"), ("ad", "false"), ("ar", "0.6"), ("ag", "0.8"), ("ab", "0.7"), ("dx", "0"), ("dy", "0")]

PO = ", ".join(f"po{i}" for i in range(12))

# The look shared with the loop (mooi-widgets.plm writes the same for the widgets in it).
INK = "pick(wg_style, if({p}_ad, if({p}_tn > 0.5, #15181c, #eef1f4), fl.engrave), #dcffe9, #16191c, #f2f5f8, #2b2722)"
ACC = "pick(wg_style, if({p}_ad, rgb({p}_ar, {p}_ag, {p}_ab), fl.phos), fl.phos, fl.ember, #a9c4dc, #b4532f)"


def facts():
    out = ["    // GENERATED by tools/gen-wlanes.py — each lane's place, size, rest and look (lib/widgets)"]
    for p, _ in LANES:
        out += [f"    fact {p}_{n} = {v}" for n, v in FACTS]
    return "\n".join(out)


def lanes():
    out = ["        // GENERATED by tools/gen-wlanes.py — the notes, GitHub, weather, system, calendar and launcher lanes"]
    for p, call in LANES:
        rz = f"wg_rk == {p}_k"
        args = dict(X=f"if({rz}, wg_sx, {p}_x)", Y=f"if({rz}, wg_sy, {p}_y)", W=f"if({rz}, wg_sw, {p}_w)",
                    H=f"if({rz}, wg_sh, {p}_h)", U=f"if({rz}, wg_ru, {p}_u)", LAY=f"{p}_lay", PLATE=f"{p}_plate",
                    HZ=f"{p}_hz", TN=f"{p}_tn")
        along = f"(wg_dk == {p}_k or (wg_dk >= 0 and wg_dksel and {p}_sel))"
        out.append(f"""        // how near the pointer is to it (the ambient rest lifts as it comes), and how seen it is
        let {p}_near = clamp(1 - max(max(0, max({p}_x - desk.cursor.x, desk.cursor.x - {p}_x - {p}_w)), max(0, max({p}_y - desk.cursor.y, desk.cursor.y - {p}_y - {p}_h))) / 220, 0, 1)
        let {p}_wake = {p}_near > 0.7
        on change {p}_wake while {p}_wake and wg_amb and {p}_on {{ wg_amb = false }}
        let {p}_base = if(editing, if({p}_gh, 0.4, 1), if(viz_still, if({p}_st < 0.5, 1, 0.35), pick({p}_k, {PO}))) * {p}_opa * (1 - 0.85 * wg_ambs * (1 - {p}_near))
        group {{
            let ink = {INK.format(p=p)}
            let acc = {ACC.format(p=p)}
            z: if({p}_beh, 1, 3)
            show: {p}_on and (editing or wg_dkp > 0.01 or {p}_st < 1.5)
            opacity: {p}_base + (1 - {p}_base) * wg_dkp
            move: if({along}, wg_dx, 0) + {p}_dx * wg_dkp, if({along}, wg_dy, 0) + {p}_dy * wg_dkp
            {call.format(**args)}
            box {{ from: {p}_x, {p}_y; size: {p}_w, {p}_h; corner: 6; stroke: 1; color: fl.trace_lit; opacity: 0.4 * wg_ambs * (1 - {p}_near) }}
        }}""")
    return "\n".join(out)


def put(text, tag, body):
    pat = re.compile(rf"( *)// <gen:{tag}>\n.*?// </gen:{tag}>", re.S)
    m = pat.search(text)
    if not m:
        raise SystemExit(f"no <gen:{tag}> block in {SCENE}")
    ind = m.group(1)
    return text[:m.start()] + f"{ind}// <gen:{tag}>\n{body}\n{ind}// </gen:{tag}>" + text[m.end():]


def main():
    text = SCENE.read_text()
    text = put(text, "lanefacts", facts())
    text = put(text, "lanes", lanes())
    SCENE.write_text(text)
    print(f"wrote the lanes in {SCENE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
