#!/usr/bin/env python3
"""Generates shell/mooi-node.plm — the Dynamic Pill as a living node (D226; spec
docs/superpowers/specs/2026-11-09-dynamic-pill-node-design.md). The logic (shell/mooi-node.luau, with the pure
engine in shell/lib/node/) decides what the node is and where its parts go; this scene only springs and draws.

One surface across the top of the screen (level top; overlay while the universe is open), taking input only
where something is drawn. The body is one shape on four springs — one per personality (organic, minimal,
technical, cyber); the logic picks which the node follows (nd_np) — and every state grows out of it.

  tools/gen-node.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "shell" / "mooi-node.plm"
WALLS = ROOT / "shell" / "mooi-walls.plm"

PERS = [("organic", 240, 17), ("minimal", 520, 42), ("technical", 640, 52), ("cyber", 760, 26)]
FIELDS = [("x", 949), ("y", 8), ("w", 22), ("h", 6), ("r", 3)]
