#!/usr/bin/env python3
"""Writes shell/mooi-arcade.plm: mooi's arcade (D276; k4's games, ported as mooi's own).

One window in the frame's colours over a dimmed desktop: a picker of the games, then the game. Every game is pure
logic under shell/lib/arcade/ (tested) and drawn here from what shell/mooi-arcade.luau writes. Super+G opens it,
Esc goes back to the picker and then closes it. Run after a change: python3 tools/gen-arcade.py
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "shell" / "mooi-arcade.plm"
WALLS = ROOT / "shell" / "mooi-walls.plm"
MONO = '"Share Tech Mono"'
SANS = '"Exo 2"'
NERD = '"CaskaydiaCove Nerd Font"'
PW, PH = 860, 600          # the window
SW, SH, CELL = 28, 18, 26   # Snake's board
KEYS = [("Escape", 27), ("Return", 13), ("Up", 38), ("Down", 40), ("Left", 37), ("Right", 39), ("space", 32),
        ("w", 87), ("a", 65), ("s", 83), ("d", 68), ("p", 80)]


def palette_block():
    lines = WALLS.read_text().split("\n")
    s = next(i for i, l in enumerate(lines) if l.strip().startswith("fact fr_ground_r"))
    e = max(i for i, l in enumerate(lines) if l.strip().startswith("follow pr_"))
    cs = [l for l in lines if l.strip().startswith(("fact c_", "fact st_", "fact cn_", "fact bar_"))]
    return lines[s:e + 1] + cs


def scene():
    L = ['language 0.9', 'import "theme/tokens.plm"', 'import "theme/ferrolume.plm"', '',
         '// GENERATED by tools/gen-arcade.py — mooi\'s arcade (D276). Do not edit: change the generator.', '',
         'scene Arcade {',
         '    permissions {',
         '        run: "pleamar", "mooi"',
         '        services: "files", "files.write", "env", "sound"',
         '    }']
    L += palette_block()
    L += ['',
          '    // ── where it is: 0 shut · 1 the picker · 2 Snake (more games take the next numbers) ──',
          '    fact ac_page = 0', '    prop ac_k = 0 ~calm', '    follow ac_k = if(ac_page > 0, 1, 0)',
          '    fact ac_sel = 0',
          '    model gm max 6 { name: text; glyph: text; line: text; best: text; ready: bool }',
          '    // ── Snake ──',
          f'    model sn max {SW * SH} {{ x: number; y: number }}',
          '    fact sn_fx = -1', '    fact sn_fy = -1', '    fact sn_hx = 0', '    fact sn_hy = 0',
          '    fact sn_state = 0      // 0 ready · 1 playing · 2 paused · 3 over · 4 won',
          '    text sn_score = "0"', '    text sn_best = "0"',
          '',
          '    event ac_cmd ->       // from `mooi arcade`: 1 open (or close) · 0 close',
          '    event ac_key ->       // a key while the arcade holds the keyboard',
          '    event ac_pick ->      // a game\'s card pressed']
    L += surface()
    L += ['}']
    return "\n".join(L) + "\n"


def surface():
    c = "        "
    ink, dim, acc = "fl.engrave", "fl.muted", "fl.phos"
    L = ['', '    surface arcade {',
         '        size: full, full', '        anchor: top', '        level: overlay', '        reserve: -1',
         '        keyboard: exclusive while ac_page > 0',
         '        rate: 60, 1 while ac_page == 0 and ac_k < 0.01',
         f'{c}let px = (arcade.width - {PW}) / 2',
         f'{c}let py = (arcade.height - {PH}) / 2 + 30 * (1 - ac_k)',
         f'{c}group {{ show: ac_k > 0.005',
         f'{c}    box {{ from: 0, 0; size: arcade.width, arcade.height; color: #000000; opacity: 0.55 * ac_k }}',
         f'{c}    zone box acz_out {{ from: 0, 0; size: arcade.width, arcade.height; role: button; label: "Close the arcade"; show: ac_page > 0 }}',
         f'{c}    on press acz_out {{ emit ac_cmd(0) }}',
         f'{c}    group {{ opacity: ac_k',
         f'{c}        body {{ color: fl.ground; shadow: 0, 16, 40, 0.5',
         f'{c}            box {{ from: px, py; size: {PW}, {PH}; corner: 22 }} }}',
         f'{c}        box {{ from: px, py; size: {PW}, {PH}; corner: 22; stroke: 1.2; color: fl.trace }}',
         f'{c}        zone box acz_in {{ from: px, py; size: {PW}, {PH}; role: region; label: "Arcade"; show: ac_page > 0 }}',
         f'{c}        text "󰊴" {{ at: px + 34, py + 34; anchor: center; size: 18; family: {NERD}; color: {acc} }}',
         f'{c}        text pick(ac_page, "", "Arcade", "Snake") {{ at: px + 56, py + 34; anchor: left center; size: 16; weight: 700; family: {SANS}; color: {ink} }}',
         f'{c}        text if(ac_page == 1, "← → CHOOSE · RETURN PLAYS · ESC CLOSES", "ESC BACK TO THE GAMES") {{ at: px + {PW} - 28, py + 34; anchor: right center; align: right; size: 9; family: {MONO}; color: {dim} }}',
         f'{c}        line {{ from: px + 20, py + 58; to: px + {PW} - 20, py + 58; width: 1; color: fl.trace_dim }}']
    L += picker(c, ink, dim, acc)
    L += snake(c, ink, dim, acc)
    L += [f'{c}    }}', f'{c}}}']
    for k, code in KEYS:
        L += [f'{c}on key {k} while ac_page > 0 {{ emit ac_key({code}) }}']
    L += ['    }']
    return L


def picker(c, ink, dim, acc):
    cw, ch = (PW - 40 - 2 * 20) / 3, 300
    L = [f'{c}        group {{ show: ac_page == 1',
         f'{c}            for g in gm {{',
         f'{c}                let gx = px + 20 + g.index * ({cw} + 20)',
         f'{c}                let gy = py + 110',
         f'{c}                let on = g.index == ac_sel',
         f'{c}                box {{ from: gx, gy; size: {cw}, {ch}; corner: 18; color: fl.well; opacity: if(on, 1, 0.7) }}',
         f'{c}                box {{ from: gx, gy; size: {cw}, {ch}; corner: 18; stroke: if(on, 2, 1); color: if(on, {acc}, fl.trace_dim) }}',
         f'{c}                text g.glyph {{ at: gx + {cw} / 2, gy + 96; anchor: center; size: 64; family: {NERD}; color: if(g.ready, {acc}, {dim}) }}',
         f'{c}                text g.name {{ at: gx + {cw} / 2, gy + 178; anchor: center; align: center; size: 18; weight: 700; family: {SANS}; color: {ink} }}',
         f'{c}                text g.line {{ at: gx + {cw} / 2, gy + 214; anchor: center; align: center; size: 11; family: {SANS}; color: {dim}; width: {cw} - 32; lines: 2 }}',
         f'{c}                text g.best {{ at: gx + {cw} / 2, gy + 268; anchor: center; align: center; size: 10; weight: 700; family: {MONO}; color: if(g.ready, {acc}, {dim}) }}',
         f'{c}                zone box acz_g {{ from: gx, gy; size: {cw}, {ch}; corner: 18; cursor: pointer; role: button; label: "{{g.name}}"; show: ac_page == 1 }}',
         f'{c}                on press acz_g {{ emit ac_pick(g.index) }}',
         f'{c}            }}',
         f'{c}        }}']
    return L


def snake(c, ink, dim, acc):
    bw, bh = SW * CELL, SH * CELL
    bx = f'px + ({PW} - {bw}) / 2'
    by = 'py + 80'
    L = [f'{c}        group {{ show: ac_page == 2',
         f'{c}            box {{ from: {bx} - 6, {by} - 6; size: {bw} + 12, {bh} + 12; corner: 12; color: fl.well }}',
         f'{c}            for s in sn {{',
         f'{c}                box {{ from: {bx} + s.x * {CELL} + 2, {by} + s.y * {CELL} + 2; size: {CELL - 4}, {CELL - 4}; corner: 6; color: {acc}; opacity: max(0.35, 1 - s.index * 0.02) }}',
         f'{c}            }}',
         f'{c}            box {{ from: {bx} + sn_hx * {CELL} + 1, {by} + sn_hy * {CELL} + 1; size: {CELL - 2}, {CELL - 2}; corner: 7; color: {acc}; show: sn.count > 0 }}',
         f'{c}            group {{ show: sn_fx >= 0',
         f'{c}                ellipse {{ at: {bx} + sn_fx * {CELL} + {CELL / 2}, {by} + sn_fy * {CELL} + {CELL / 2}; radius: {CELL / 2 - 4}; color: fl.ember }} }}',
         f'{c}            text "SCORE {{sn_score}}" {{ at: {bx}, py + {PH} - 34; anchor: left center; size: 12; weight: 700; family: {MONO}; color: {ink} }}',
         f'{c}            text "BEST {{sn_best}}" {{ at: {bx} + {bw}, py + {PH} - 34; anchor: right center; align: right; size: 12; weight: 700; family: {MONO}; color: {dim} }}',
         f'{c}            group {{ show: sn_state != 1',
         f'{c}                box {{ from: {bx} - 6, {by} - 6; size: {bw} + 12, {bh} + 12; corner: 12; color: fl.ground; opacity: 0.72 }}',
         f'{c}                text pick(sn_state, "Ready", "", "Paused", "Game over", "You filled the board") {{ at: px + {PW} / 2, {by} + {bh} / 2 - 16; anchor: center; align: center; size: 26; weight: 700; family: {SANS}; color: if(sn_state == 3, fl.ember, {acc}) }}',
         f'{c}                text if(sn_state == 2, "SPACE OR P GOES ON", "ARROWS OR WASD STEER · SPACE STARTS") {{ at: px + {PW} / 2, {by} + {bh} / 2 + 22; anchor: center; align: center; size: 11; family: {MONO}; color: {dim} }} }}',
         f'{c}        }}']
    return L


if __name__ == "__main__":
    OUT.write_text(scene())
    print(f"wrote {OUT.relative_to(ROOT)}")
