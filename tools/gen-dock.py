#!/usr/bin/env python3
"""Writes shell/mooi-dock.plm: the dock (D280; k4's Dual mode's dock, ported).

A row of apps rising out of the frame's bottom edge, in the frame's fill and edge with concave fillets where it
leaves the band: pinned apps, then whatever runs. A press brings an app forward (again: its next window) or starts
it; a right press pins or unpins it. It hides until the pointer touches the bottom edge, or stays while the
workspace is empty. The logic is shell/mooi-dock.luau and lib/dock. Run after a change: python3 tools/gen-dock.py
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "shell" / "mooi-dock.plm"
WALLS = ROOT / "shell" / "mooi-walls.plm"
MONO = '"Share Tech Mono"'
SANS = '"Exo 2"'
MAX = 14
SLOT = 58      # one item's width
ICON = 40
BH = 70        # the dock's height out of the edge
FR = 18        # the concave fillet where it leaves the band


def palette_block():
    lines = WALLS.read_text().split("\n")
    s = next(i for i, l in enumerate(lines) if l.strip().startswith("fact fr_ground_r"))
    e = max(i for i, l in enumerate(lines) if l.strip().startswith("follow pr_"))
    cs = [l for l in lines if l.strip().startswith(("fact c_", "fact st_", "fact cn_", "fact bar_"))]
    return lines[s:e + 1] + cs


def scene():
    L = ['language 0.9', 'import "theme/tokens.plm"', 'import "theme/ferrolume.plm"', '',
         '// GENERATED by tools/gen-dock.py — the dock (D280). Do not edit: change the generator.', '',
         'scene Dock {',
         '    permissions {',
         '        run: "pleamar", "hyprctl"',
         '        services: "files", "files.write", "env", "apps", "apps.launch", "workspaces", "window"',
         '    }']
    L += palette_block()
    L += ['',
          f'    model it max {MAX} {{ name: text; icon: image {ICON}, {ICON}; iconed: bool; letter: text; n: number; active: bool; pinned: bool }}',
          '    fact dk_show = false     // the logic: shown (the pointer at the edge, or an empty workspace)',
          '    prop dk_k = 0 ~calm', '    follow dk_k = if(dk_show, 1, 0)',
          '',
          '    event dk_hover ->        // 1 the pointer touched the edge or is on the dock · 0 it left',
          '    event dk_press ->        // an item pressed: its index',
          '    event dk_pin ->          // an item pressed with the right button: pin it or let it go',
          '    event dk_hold ->         // `mooi dock` (Super+Shift+D): held up until asked again']
    L += surface()
    L += ['}']
    return "\n".join(L) + "\n"


def surface():
    c = "        "
    ink, dim, acc = "fl.engrave", "fl.muted", "fl.phos"
    L = ['', '    surface dock {',
         f'        size: full, {BH + 60}', '        anchor: bottom', '        level: top', '        reserve: -1',
         '        rate: 60, 1 while not dk_show and dk_k < 0.01',
         f'{c}let dw = it.count * {SLOT} + 24',
         f'{c}let dx0 = (dock.width - dw) / 2',
         f'{c}let dx1 = dx0 + dw',
         f'{c}let dtop = dock.height - {BH} * dk_k',
         f'{c}let dbot = dock.height',
         f'{c}// the edge\'s sensor: the pointer touching the bottom shows the dock',
         f'{c}zone box dkz_edge {{ from: 0, dock.height - 2; size: dock.width, 2; show: not dk_show }}',
         f'{c}on enter dkz_edge {{ emit dk_hover(1) }}',
         f'{c}group {{ show: dk_k > 0.005 and it.count > 0',
         f'{c}    body {{ color: fl.ground; shadow: 0, -4, 22, 0.4',
         f'{c}        path {{',
         f'{c}            move dx0 - {FR}, dbot',
         f'{c}            curve dx0, dbot - {FR} via dx0, dbot',
         f'{c}            line dx0, dtop + 16',
         f'{c}            curve dx0 + 16, dtop via dx0, dtop',
         f'{c}            line dx1 - 16, dtop',
         f'{c}            curve dx1, dtop + 16 via dx1, dtop',
         f'{c}            line dx1, dbot - {FR}',
         f'{c}            curve dx1 + {FR}, dbot via dx1, dbot',
         f'{c}            close }} }}',
         f'{c}    path {{ stroke: 1.2; color: fl.trace; opacity: 0.9',
         f'{c}        move dx0 - {FR}, dbot',
         f'{c}        curve dx0, dbot - {FR} via dx0, dbot',
         f'{c}        line dx0, dtop + 16',
         f'{c}        curve dx0 + 16, dtop via dx0, dtop',
         f'{c}        line dx1 - 16, dtop',
         f'{c}        curve dx1, dtop + 16 via dx1, dtop',
         f'{c}        line dx1, dbot - {FR}',
         f'{c}        curve dx1 + {FR}, dbot via dx1, dbot }}',
         f'{c}    // the dock as a whole holds it up while the pointer is on it',
         f'{c}    zone box dkz_body {{ from: dx0, dtop; size: dw, {BH}; show: dk_show }}',
         f'{c}    on enter dkz_body {{ emit dk_hover(1) }}',
         f'{c}    on leave dkz_body {{ emit dk_hover(0) }}',
         f'{c}    for i in it {{',
         f'{c}        let ix = dx0 + 12 + i.index * {SLOT} + {SLOT} / 2',
         f'{c}        let iy = dtop + {BH} / 2 - 4',
         f'{c}        box {{ from: ix - {SLOT / 2 - 3}, iy - {ICON / 2 + 6}; size: {SLOT - 6}, {ICON + 12}; corner: 12; color: {acc}; opacity: if(i.active, 0.18, if(dkz_i.hover, 0.1, 0)) }}',
         f'{c}        // the app\'s initial on a soft tile, and its icon over it: an icon that cannot be found leaves the letter',
         f'{c}        box {{ from: ix - {ICON / 2}, iy - {ICON / 2}; size: {ICON}, {ICON}; corner: 10; color: fl.well; opacity: 0.55 }}',
         f'{c}        text i.letter {{ at: ix, iy; anchor: center; align: center; size: 18; weight: 700; family: {SANS}; color: {ink} }}',
         f'{c}        image i.icon {{ at: ix - {ICON / 2}, iy - {ICON / 2}; size: {ICON}, {ICON}; show: i.iconed }}',
         f'{c}        // a dot for each window, up to three; the app with the focus wears them in the accent',
         f'{c}        ellipse {{ at: ix, iy + {ICON / 2 + 8}; radius: 2.2; color: if(i.active, {acc}, {dim}); show: i.n == 1 }}',
         f'{c}        ellipse {{ at: ix - 4, iy + {ICON / 2 + 8}; radius: 2.2; color: if(i.active, {acc}, {dim}); show: i.n == 2 }}',
         f'{c}        ellipse {{ at: ix + 4, iy + {ICON / 2 + 8}; radius: 2.2; color: if(i.active, {acc}, {dim}); show: i.n == 2 }}',
         f'{c}        ellipse {{ at: ix - 7, iy + {ICON / 2 + 8}; radius: 2.2; color: if(i.active, {acc}, {dim}); show: i.n >= 3 }}',
         f'{c}        ellipse {{ at: ix, iy + {ICON / 2 + 8}; radius: 2.2; color: if(i.active, {acc}, {dim}); show: i.n >= 3 }}',
         f'{c}        ellipse {{ at: ix + 7, iy + {ICON / 2 + 8}; radius: 2.2; color: if(i.active, {acc}, {dim}); show: i.n >= 3 }}',
         f'{c}        // its name above it while the pointer is on it',
         f'{c}        group {{ show: dkz_i.hover',
         f'{c}            box {{ from: ix - 70, dtop - 34; size: 140, 24; corner: 12; color: fl.ground; opacity: 0.95 }}',
         f'{c}            box {{ from: ix - 70, dtop - 34; size: 140, 24; corner: 12; stroke: 1; color: fl.trace_dim }}',
         f'{c}            text i.name {{ at: ix, dtop - 22; anchor: center; align: center; size: 10; weight: 700; family: {SANS}; color: {ink}; width: 128; lines: 1 }} }}',
         f'{c}        zone box dkz_i {{ from: ix - {SLOT / 2}, dtop; size: {SLOT}, {BH}; cursor: pointer; role: button; label: "{{i.name}}"; show: dk_show }}',
         f'{c}        on press dkz_i {{ emit dk_press(i.index) }}',
         f'{c}        on press right dkz_i {{ emit dk_pin(i.index) }}',
         f'{c}    }}',
         f'{c}}}',
         '    }']
    return L


if __name__ == "__main__":
    OUT.write_text(scene())
    print(f"wrote {OUT.relative_to(ROOT)}")
